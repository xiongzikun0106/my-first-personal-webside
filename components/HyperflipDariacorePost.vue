<section id="name">
  <div class="secno">SECTION 05</div>
  <h2>hyperflip：一个<em>没有主人</em>的名字的漂流</h2>
  <p class="lead">2022 年 1 月 12 日，leroy 发推否认自己在做 dariacore（日媒记录为「私は Dariacore を作っていない」），场景一片哗然<sup><a href="#ref-14">[14]</a></sup>。此后「受影响的声音到底叫什么」成了悬案——而解决方案，来自推特上的一次即兴命名。</p>

  <div class="tl">
    <div class="item"><div class="y">2022.01.12</div><div class="d">leroy 否认 dariacore；欧美场景开始寻找替代名，部分艺术家撤下 dariacore 标签<sup><a href="#ref-14">[14]</a></sup><sup><a href="#ref-1">[1]</a></sup></div></div>
    <div class="item"><div class="y">2022.02.06</div><div class="d">JazzPutin 发推问「leroy 的流派到底叫什么」；用户回复：「有人——我猜是 schnozz——把它命名为 <b>hyperflip</b>，这名字真棒」<sup><a href="#ref-14">[14]</a></sup></div></div>
    <div class="item"><div class="y">2022.03.06</div><div class="d">推文反映当时状态：「leroy 否认 dariacore 标签后没人知道该怎么称呼整个子流派了；hyperflip 很酷，但不是人人都在用」<sup><a href="#ref-14">[14]</a></sup></div></div>
