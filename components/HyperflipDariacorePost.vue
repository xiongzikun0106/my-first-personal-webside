    <h4>命名即拒绝：一场预谋的误会</h4>
    <p style="margin:0">一个耐人寻味的细节：整个「○○core」命名游戏（把任何东西加个 -core 后缀就宣称新体裁）正是 leroy 在反讽的对象。终章最后一曲《Dariacore Song Tutorial》竟是摇滚，仿佛在说「你们把我这当体裁是吧？」；她的作品里反复出现「fucking garbage」人声采样。有日本研究者由此猜测：<em>dariacore 是一个犬儒的「假体裁」——讽刺一切都被加 core、一切都被体裁化</em><sup><a href="#ref-14">[14]</a></sup>。然而玩笑脱靶了：世界真的把它当成了体裁，还给它造出了成千上万首「垃圾」。这场「玩笑的失控」——即作者意图与命名权力的分离——是理解后面所有故事的关键。</p>
