    <li><span class="term"><b>注意力经济下的命名军备竞赛。</b></span>当「新体裁」是涨粉捷径，人人都在抢注名字（「hyperplugg CEO」式的自我加冕已成梗）<sup><a href="#ref-13">[13]</a></sup>；dariacore 则演示了另一种可能：<b>名字脱离创作者、脱离原意，自己长成一场运动</b>。</li>
    <li><span class="term"><b>碎片化记忆与数字怀旧。</b></span>采样的对象不是「某首歌」而是「一段记忆的格式」：2010s EDM Drop、2000s 电视、早期网络梗。note.com 的追问——这「垃圾箱」装的是 SoundClown 的废料，还是<b>把青春期耗在网上的那一代人碎成片的记忆</b>？<sup><a href="#ref-14">[14]</a></sup></li>
    <li><span class="term"><b>全球本土化（glocal）传播。</b></span>一个美国 bedroom 玩笑 → 日本俱乐部场景：同样的语法，不同的素材库与「土壤」。名称（dariacore→hyperflip）、场所（卧室→夜店）、音色（meme→音割れ）都在翻译中变异——互联网亚文化的标准漂流路线<sup><a href="#ref-14">[14]</a></sup><sup><a href="#ref-4">[4]</a></sup>。</li>
    <li><span class="term"><b>标签焦虑（taxonomy anxiety）。</b></span>场景里弥漫着对「别人怎么看我们、这算什么体裁」的焦虑（steej 所言）<sup><a href="#ref-4">[4]</a></sup>；创作者反复声明「这不是 genre」。这是网生代对<b>被归类</b>的本能抵触——与 hyperpop 的自我否认一脉相承<sup><a href="#ref-11">[11]</a></sup>。</li>
  </ul>
