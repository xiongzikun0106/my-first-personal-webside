  <div class="secno">SECTION 02</div>
  <h2>前史：hyperpop 世代与「<span class="hl">没有名字的</span>」声音</h2>
  <p class="lead">dariacore/hyperflip 不是凭空冒出来的。要理解它，必须先看它爹妈：PC Music 时代的 hyperpop，以及疫情卧室里的 digicore。</p>

  <h3>2.1 从 PC Music 到 Spotify 歌单：hyperpop 的两种出生证</h3>
  <p><strong>hyperpop</strong> 是对 21 世纪流行音乐配方进行<b>夸张化、最大化（maximalist）</b>处理的电子流行运动，发端于 2010 年代初的英国<sup><a href="#ref-3">[3]</a></sup>。它最早的核来自伦敦厂牌/艺术团体 <strong>PC Music</strong>（A. G. Cook、SOPHIE、GFOTY、Hannah Diamond 等）——一种把泡泡糖流行、Eurohouse、J-pop、nightcore 与离奇合成器熔在一起、被戏称为「bubblegum bass」的声音<sup><a href="#ref-3">[3]</a></sup><sup><a href="#ref-12">[12]</a></sup>。</p>
  <p>2019 年前后，<strong>100 gecs</strong> 的病毒式走红让 hyperpop 进入 TikTok 一代；而它成为「体裁」，很大程度上要归功于<b>算法</b>：Spotify 数据工程师 Glenn McDonald 先于 2018 年把 "hyperpop" 写进平台音乐元数据（他运营着类型数据库 Every Noise at Once），随后编辑 Lizzy Szabo 推出同名官方歌单<sup><a href="#ref-3">[3]</a></sup>。用 NPR 的话说：hyperpop「始于一个播放列表」——它几乎<b>不存在于平台之外</b>，本质上是「平台自身编程逻辑」的产物<sup><a href="#ref-12">[12]</a></sup>。</p>

  <h3>2.2 疫情卧室：digicore / glitchcore 一代</h3>
  <p>2020 年疫情封锁把互联网青少年关进卧室，也把 SoundCloud、Discord 变成新式「食堂餐桌」：被称作 digicore / glitchcore 的圈层里，十几岁的创作者用 FL Studio 批量产歌、在游戏里办虚拟演出、靠 TikTok 传播<sup><a href="#ref-11">[11]</a></sup><sup><a href="#ref-8">[8]</a></sup>。到 2020 年底，这股「数字核心」音乐让 Twitter 陷入无尽话语战，也上了 Spotify 最热歌单——随后很快迎来反噬：<strong>hyperpop 成了「一个拒绝承认自己存在的场景」</strong>，有人称这个词为「绰号」甚至「脏话」，Charli XCX 在 2020 年发了那条著名的推文：「what is hyperpop?」<sup><a href="#ref-11">[11]</a></sup></p>
  <p>dariacore 与 hyperflip 正是这场身份危机里长出的「次生代」：它们<b>站在 hyperpop 的肩膀上，却拒绝它的名字</b>。hyperpop 想「成为音乐本身」<sup><a href="#ref-12">[12]</a></sup>；dariacore 的创始人后来却说，那只是个「持续太久的玩笑」<sup><a href="#ref-2">[2]</a></sup>。</p>

  <figure class="q">
    <blockquote>「hyperpop 是一个棘手的、什么都能装的词：一种过度与媚俗被吹爆的音乐，不惧怕彻底的机械化或‘低级趣味’，<b>追寻的是那个解离的线上自我（dissociated online self）的声音</b>。」</blockquote>
    <figcaption>—— Sheldon Pearce, NPR《Anatomy of a microgenre》, 2025<sup><a href="#ref-12">[12]</a></sup></figcaption>
  </figure>
