  <h2>Dariacore：一张<em>垃圾</em>封面与一场「玩笑式发明」</h2>

  <h3>4.1 起点：2020 年 12 月 2 日的 <em>ricky bobby</em></h3>
  <p>故事从一条 SoundCloud 开始。2020 年 12 月 2 日，一个叫 <strong>leroy</strong>（全小写）的账号上传了《ricky bobby》——一段把流行乐剪碎、用 Jersey club 律动重新驱动的疯狂混音。此后 leroy 连续发布多首同风格曲目，并于 2021 年 5 月 14 日汇成专辑《Dariacore》<sup><a href="#ref-14">[14]</a></sup><sup><a href="#ref-2">[2]</a></sup>。16 首曲目全部小写、总长仅 29 分钟：<em>ricky bobby / 2008 / copyright strike my fucking nuts / virginity rockstar / die in my dream</em>……封面是从 MTV 成人动画《Daria》（1997–2002）里截的图<sup><a href="#ref-1">[1]</a></sup><sup><a href="#ref-2">[2]</a></sup>。没有厂牌，没有宣传，纯自发行。</p>

