  <p class="lead">这几个小时的采样狂欢，其实踩中了当代美学争论的每一个雷区。</p>

  <h3>10.1 本体论：原作死了吗？——拼贴与拟像</h3>
  <p>当 Billie Eilish 被切成 0.3 秒的碎片、再与迪士尼音效焊在一起，追问「哪一段是原作」就变得荒谬。dariacore 把 <b>plunderphonics</b>（John Oswald 1985 年提出的「以盗用为作曲特权」的采样拼贴实践<sup><a href="#ref-22">[22]</a></sup>）从学院实验拖进 meme 沼泽，让「原作/复制」这对形而上学范畴彻底失灵。用鲍德里亚的话说，它生产的是<b>拟像</b>：不是对真实的摹写，而是对「已被复制的流行」的再复制、再加速——比流行更流行、比真实更亢奋的超真实。而詹明信（Fredric Jameson）关于后现代「<b>拼贴（pastiche）取代戏仿</b>、历史感扁平化为风格超市」的诊断<sup><a href="#ref-25">[25]</a></sup>，在这里获得了最通俗的注脚：整部流行乐史变成一个随取随用的<b>素材超市</b>。这条谱系也有清晰的文献坐标：从 John Oswald 1985 年把「盗用录音作为作曲特权」写进论文的 plunderphonics<sup><a href="#ref-24">[24]</a></sup>，到 mashup 研究的「可配置文化」（Sinnreich）与「remix 之后的伦理美学」（Gunkel）<sup><a href="#ref-29">[29]</a></sup>；vaporwave 一系（Adam Harper 的加速主义解读、Grafton Tanner 的「商品化的幽灵」）则提供了「数字怀旧如何成为商品」的平行案例<sup><a href="#ref-27">[27]</a></sup><sup><a href="#ref-28">[28]</a></sup>。</p>

  <h3>10.2 作者性：人格的链式生产</h3>
  <p>leroy / dltzk / Jane Remover 不是三个名字，而是三套<b>人格-作品系统</b>；dariacore 的作者本人主动让渡了对体裁的命名权（甚至否认它）；hyperflip 则从未有作者。这与本雅明的灵光（aura）叙事正相反：数字原住民在<b>去中心化的署名游戏</b>里长大，作者身份是「一件可以穿脱的皮肤」。NPR 指出 hyperpop 的底线共识是「重要的是做了什么，而不是谁做的」<sup><a href="#ref-12">[12]</a></sup>——这或许是面对 AI 生成时代的一种提前排练。</p>

  <h3>10.3 反讽之后：真诚如何可能？</h3>
  <p>这张专辑叫《copyright strike my fucking nuts》，那句人声采样说「fucking garbage」，Daria 本人是 90 年代流行文化里最著名的犬儒少女——一切都指向<b>后反讽（post-irony）</b>地带：<em>用最夸张的戏仿音量，喊出最真实的情感</em>。Jane Remover 在《Frailty》中用同类语汇书写青春期心碎与性别不安（dysphoria），被 Pitchfork 盛赞<sup><a href="#ref-5">[5]</a></sup>；hyperpop 社群同样借变声与失真探索性别表达<sup><a href="#ref-3">[3]</a></sup>。戏仿与真诚并不矛盾——这正是网生代处理「一切都已被说尽」处境的方式：<b>先假装它是垃圾，才有资格把它当真。</b>digicore 成员 d0llywood1 有句被 Rolling Stone UK 引用的自白可作注脚：「我们都是数字小孩，在网上相遇，所以做出的音乐<b>听起来就像我们在网上捡到的东西</b>」<sup><a href="#ref-17">[17]</a></sup>——把「网络捡垃圾」从自嘲升级为创作纲领，正是这个世代的表情。</p>

  <h3>10.4 时间性：加速、怀旧与「失去的未来」</h3>
  <p>nightcore 式提速与 BPM 200+ 是<b>加速</b>的听觉图腾；而采样对象（2010s 流行、00s 动画）暴露了<b>数字怀旧</b>。Mark Fisher 笔下的「失去的未来」（hauntology）<sup><a href="#ref-31">[31]</a></sup>在 vaporwave 那里是对资本主义许诺之未来的悼念；在 dariacore 这里则更轻快也更虚无：<b>过去没有变成废墟，而是变成可随时重播、加速、切成 meme 的缓存</b>。时间被压平成「此刻的素材库」——连同其间的情绪。另一点相反的证据也耐人寻味：Dariacore 2 起曲目变长、趋向俱乐部，「时间感」从短视频回归身体节奏；终章甚至出现 drone 段落——极速之后，是悬停<sup><a href="#ref-14">[14]</a></sup>。</p>

  <h3>10.5 命名的形而上学：词与世界</h3>
  <p>Fisher 说命名生产「剩余价值」<sup><a href="#ref-23">[23]</a></sup>，No Bells 用它解释 SoundCloud 的造词狂热<sup><a href="#ref-13">[13]</a></sup>；dariacore 的整个故事则是它的反向实验：一个被否认的名字（dariacore）、一个无主的名字（hyperflip）仍各自长成真实的声音运动——说明<b>在互联网时代，名称与所指之间只剩脆弱的约定，而约定本身会被流量、地域与社群重新书写</b>。体裁由此不再是分类学，而是<b>社会学</b>。</p>
</section>

