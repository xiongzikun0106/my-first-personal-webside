  <div class="secno">SECTION 01</div>
  <h2>导语：当「体裁」从分类工具变成<em>玩具</em></h2>
  <p class="lead">二十一世纪的第三个十年，互联网音乐的奇观之一，是<b>微体裁（microgenre）</b>像 meme 一样批量出生、批量死亡：glitchcore、digicore、robloxcore、sigilkore、hexD、rage、krushclub…… 其中有两个词始终互相纠缠、彼此偷换，连创作者自己都拒绝承认——<strong>dariacore</strong> 与 <strong>hyperflip</strong>。</p>
  <p>它们常被一并描述为：<b>把 2000s–2010s 的流行音乐与 EDM 切成碎片，和网络梗、动画采样、警报声与车祸音效焊在一起，用 Jersey club 的弹性律动与 dubstep 的 Drop 重新驱动，以 200 BPM 上下的疯狂速度倾泻而出</b>的「混搭狂欢」<sup><a href="#ref-1">[1]</a></sup>。它被称作「加了类固醇的流行乐」<sup><a href="#ref-7">[7]</a></sup>、「流行乐炸弹」；听感像「电脑得了大肠杆菌后呕吐出胆汁」<sup><a href="#ref-4">[4]</a></sup>——然而在失序的表面之下，是高度讲究的采样编织与节奏工程。</p>
  <p>这两个词最迷人的地方在于：<em>它们几乎没有可被客观定义的差异，却拥有两条截然不同的历史。</em>dariacore 是一次具体的、可以被指认的「命名事件」（一张专辑、一部 90 年代动画、一个后来反悔的作者）；hyperflip 则是一次漫长的、没有主人的「命名漂流」——从美国 SoundCloud 角落漂到东京俱乐部，最后在一个与它无关的国家落地生根。研究它们，等于研究<b>互联网时代「名称」本身如何成为文化生产的引擎</b>。</p>
  <div class="callout">
    <h4>阅读提示</h4>
    <p style="margin:0">本文综合英文与日文一手/二手资料（维基百科、Pitchfork、The FADER、Insider/No Bells、日本 Lost Frog 系报道等），所有关键论断均以 <sup style="color:var(--gold)">[n]</sup> 标注出处并附链接。文中「dariacore / hyperflip」作为<b>互联网亚文化对象</b>讨论，乐评与场景内部对其定义仍存在分歧——分歧本身，正是本文的主题之一。</p>
